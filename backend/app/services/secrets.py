"""Encryption at rest for secrets stored in the database (e.g. an admin-uploaded Anthropic API key) and for private
account data (search preferences, saved places; see seal/unseal).

Key material: FOODACCESS_SECRET_KEY (a Fernet key) if set — required in production — otherwise a local key file
data/secret.key created with 0600 permissions on first use (development convenience; git-ignored).
"""
import base64
import hashlib
import json
import logging
import os

from cryptography.fernet import Fernet, InvalidToken

from app.config import get_settings


class SecretUnavailable(Exception):
    pass


def _fernet() -> Fernet:
    s = get_settings()
    key = s.secret_key
    if not key:
        if s.environment == "production":
            raise SecretUnavailable("Set FOODACCESS_SECRET_KEY to store secrets in production")
        path = s.data_dir / "secret.key"
        if not path.exists():
            path.parent.mkdir(parents=True, exist_ok=True)
            fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
            with os.fdopen(fd, "wb") as fh:
                fh.write(Fernet.generate_key())
        key = path.read_text().strip()
    raw = key.encode() if isinstance(key, str) else key
    try:
        return Fernet(raw)
    except ValueError:
        # Not a Fernet key (e.g. a random secret generated by the hosting platform): derive one from it.
        return Fernet(base64.urlsafe_b64encode(hashlib.sha256(raw).digest()))


def encrypt(value: str) -> str:
    return _fernet().encrypt(value.encode()).decode()


def decrypt(token: str) -> str:
    try:
        return _fernet().decrypt(token.encode()).decode()
    except InvalidToken as e:
        raise SecretUnavailable("Stored secret cannot be decrypted (was FOODACCESS_SECRET_KEY changed?)") from e


# --- private account data -------------------------------------------------------------------------------------------

log = logging.getLogger(__name__)
SEALED = "_enc"
_warned = False


def available() -> bool:
    """Whether an encryption key is configured (always true outside production: a local key file is created)."""
    try:
        _fernet()
        return True
    except SecretUnavailable:
        return False


def is_sealed(stored) -> bool:
    return isinstance(stored, dict) and set(stored) == {SEALED}


def seal(value):
    """Encrypt a JSON-serialisable value for storage: {"_enc": "<token>"}.

    Without a key (production with FOODACCESS_SECRET_KEY unset) the value is stored as it is, with a logged warning, so
    accounts keep working; `foodaccess bootstrap` seals such rows once a key is set."""
    global _warned
    try:
        return {SEALED: encrypt(json.dumps(value, separators=(",", ":")))}
    except SecretUnavailable:
        if not _warned:
            log.warning("FOODACCESS_SECRET_KEY is not set: private account data is being stored UNENCRYPTED")
            _warned = True
        return value


def unseal(stored, default=None):
    """Reverse of seal(). Plain (not yet sealed) values pass through. A value that cannot be decrypted (the key was
    changed or removed) yields `default` instead of breaking sign-in."""
    if not is_sealed(stored):
        return stored
    try:
        return json.loads(decrypt(stored[SEALED]))
    except (SecretUnavailable, ValueError):
        log.error("Private account data could not be decrypted (was FOODACCESS_SECRET_KEY changed?)")
        return default
